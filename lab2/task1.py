# -*- coding: utf-8 -*-
"""
Проверка теоремы Котельникова (Шеннона–Найквиста) на тестовом сигнале
x(t) = sin(ω0 t).

Идея:
1) задаём непрерывный синусоидальный сигнал;
2) выбираем частоту дискретизации fs, удовлетворяющую условию fs > 2 f0;
3) берём отсчёты x[n] = x(nT), где T = 1 / fs;
4) восстанавливаем сигнал по отсчётам с помощью sinc-интерполяции;
5) сравниваем исходный и восстановленный сигналы на графике.

Важно:
- numpy.sinc(z) реализует sinc(z) = sin(pi z) / (pi z).
- Формула восстановления Шеннона записывается именно через такую sinc.
- Для уменьшения краевых эффектов при численной реализации берётся
  чуть более широкий набор отсчётов, чем интервал визуализации.
"""

import numpy as np
import matplotlib.pyplot as plt


# ============================================================
# Параметры исходного непрерывного сигнала
# ============================================================

A = 1.0              # амплитуда синуса
f0 = 5.0             # частота синуса в Гц
omega0 = 2 * np.pi * f0   # круговая частота ω0 в рад/с

# Сигнал: x(t) = A * sin(ω0 t)


# ============================================================
# Параметры дискретизации
# ============================================================

# Выбираем частоту дискретизации, удовлетворяющую теореме Котельникова:
# fs > 2 * f0
fs = 50.0            # частота дискретизации в Гц
T = 1.0 / fs         # шаг дискретизации

nyquist_freq = fs / 2.0

print(f"f0 = {f0} Гц")
print(f"fs = {fs} Гц")
print(f"Частота Найквиста fs/2 = {nyquist_freq} Гц")
print(f"Условие теоремы Котельникова выполняется: {fs > 2 * f0}")


# ============================================================
# Интервал, на котором строим график
# ============================================================
t_plot_min = 0.0
t_plot_max = 2.0

# Для более качественной sinc-реконструкции берём отсчёты на расширенном
# интервале. Это уменьшает краевые эффекты, потому что идеальная формула
# предполагает бесконечное число отсчётов по всей оси времени.
t_sample_min = -2.0
t_sample_max = 4.0


# ============================================================
# Формирование дискретных отсчётов
# ============================================================
# Номер первого и последнего отсчёта на расширенном интервале.
n_min = int(np.floor(t_sample_min / T))
n_max = int(np.ceil(t_sample_max / T))
# Массив индексов дискретизации: n = n_min, ..., n_max
n = np.arange(n_min, n_max + 1)

# Времена отсчётов: t_n = nT
t_samples = n * T

# Значения исходного сигнала в точках отсчёта
x_samples = A * np.sin(omega0 * t_samples)


# ============================================================
# Исходный сигнал на плотной временной сетке
# ============================================================
t_dense = np.linspace(t_plot_min, t_plot_max, 4000)
x_true = A * np.sin(omega0 * t_dense)


# ============================================================
# Восстановление сигнала по формуле Котельникова
# ============================================================
def sinc_reconstruct(t_eval: np.ndarray,
                     t_s: np.ndarray,
                     x_s: np.ndarray,
                     T: float) -> np.ndarray:
    """
    Восстановление непрерывного сигнала по дискретным отсчётам
    методом sinc-интерполяции.

    Формула:
        x(t) = sum_n x[n] * sinc((t - nT) / T)

    где np.sinc(z) = sin(pi z) / (pi z).

    Параметры:
        t_eval : точки времени, в которых вычисляется восстановленный сигнал
        t_s: времена отсчётов
        x_s: значения отсчётов
        T: шаг дискретизации

    Возвращает:
        Восстановленный сигнал в точках t_eval.
    """
    # Матрица аргументов sinc:
    # для каждой точки t_eval и каждого отсчёта t_s
    # z = (t - t_s) / T
    z = (t_eval[None, :] - t_s[:, None]) / T

    # Каждая строка соответствует вкладу одного отсчёта:
    # x_s[i] * sinc((t - t_s[i]) / T)
    contributions = x_s[:, None] * np.sinc(z)

    # Суммируем по всем отсчётам
    return np.sum(contributions, axis=0)


x_reconstructed = sinc_reconstruct(t_dense, t_samples, x_samples, T)


# ============================================================
# Оценка ошибки восстановления на интервале визуализации
# ============================================================
mse = np.mean((x_true - x_reconstructed) ** 2)
max_abs_err = np.max(np.abs(x_true - x_reconstructed))

print(f"MSE на интервале визуализации: {mse:.3e}")
print(f"Максимальная абсолютная ошибка: {max_abs_err:.3e}")


# ============================================================
# Визуализация
# ============================================================
plt.figure(figsize=(12, 6))

# Исходный непрерывный сигнал
plt.plot(t_dense, x_true, label="Исходный сигнал x(t)", linewidth=2)

# Восстановленный сигнал
plt.plot(t_dense, x_reconstructed, "--", label="Восстановленный по отсчётам", linewidth=2)

# Отсчёты показываем отдельными точками.
# Чтобы не перегружать график, выведем только те отсчёты, которые попадают
# в отображаемый интервал.
mask_visible = (t_samples >= t_plot_min) & (t_samples <= t_plot_max)
plt.scatter(
    t_samples[mask_visible],
    x_samples[mask_visible],
    s=25,
    label="Дискретные отсчёты",
    zorder=3
)

plt.title("Проверка теоремы Котельникова на сигнале x(t) = sin(ω0 t)")
plt.xlabel("t, c")
plt.ylabel("x(t)")
plt.grid(True, alpha=0.35)
plt.legend()
plt.tight_layout()
plt.show()
